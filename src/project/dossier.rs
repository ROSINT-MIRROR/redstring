use std::collections::BTreeSet;

use crate::error::Error;
use crate::model::{
    CaseFile, EntityRec, FACET_META, Facet, KIND_META, ObsValue, Origin, RELATION_META, ROLE_META,
    RelationRec, Role, SOURCE_META, SOURCE_TIER_META, Source, occupation_of, pretty_key, role_of,
    status_label, subtype_of, subtype_value,
};

use super::derive::{SEALED_LABEL, redact};
use super::io::read_note;
use super::layout::Project;

const FOOTER: &str = "\n---\nRegenerated by redstring on every save — do not edit.\n";

pub fn write_dossiers(project: &Project, cf: &CaseFile) -> Result<(), Error> {
    let public = redact(cf)?;
    let mut sealed_reals: BTreeSet<String> = BTreeSet::new();
    for e in &cf.data.entities {
        if e.sealed {
            sealed_reals.insert(e.slug.clone());
        }
    }
    let dir = project.root.join("entities");
    let rd = match std::fs::read_dir(&dir) {
        Ok(r) => r,
        Err(source) if source.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(source) => return Err(Error::Io { path: dir, source }),
    };
    let mut slugs: Vec<String> = Vec::new();
    for entry in rd {
        let entry = entry.map_err(|source| Error::Io { path: dir.to_path_buf(), source })?;
        let ft = entry
            .file_type()
            .map_err(|source| Error::Io { path: entry.path(), source })?;
        if !ft.is_dir() {
            continue;
        }
        let Some(slug) = entry.file_name().to_str().map(str::to_owned) else {
            continue;
        };
        slugs.push(slug);
    }
    slugs.sort();
    for slug in &slugs {
        let Some(text) = dossier_for(project, &public, slug, &sealed_reals)? else {
            continue;
        };
        let path = project.entity_dir(slug)?.join("dossier.md");
        std::fs::write(&path, text).map_err(|source| Error::Io { path, source })?;
    }
    Ok(())
}

fn dossier_for(
    project: &Project,
    public: &CaseFile,
    slug: &str,
    sealed_reals: &BTreeSet<String>,
) -> Result<Option<String>, Error> {
    if sealed_reals.contains(slug) {
        return Ok(Some(sealed_stub()));
    }
    let Some(e) = public.data.entities.iter().find(|e| e.slug == slug) else {
        return Ok(None);
    };
    if e.label == SEALED_LABEL {
        return Ok(Some(sealed_stub()));
    }
    Ok(Some(render_entity(project, public, e)?))
}

fn sealed_stub() -> String {
    format!(
        "# {SEALED_LABEL}\n\nThis entity is sealed — its identity and evidence are redacted from public outputs.\n{FOOTER}"
    )
}

fn render_entity(project: &Project, public: &CaseFile, e: &EntityRec) -> Result<String, Error> {
    let meta = &KIND_META[e.kind as usize];
    let mut out = String::new();
    out.push_str(&format!("# {} {}\n\n", meta.icon, e.label));
    out.push_str(&format!("- **Kind:** {}\n", meta.label));
    if !e.value.is_empty() {
        out.push_str(&format!("- **Value:** `{}`\n", e.value));
    }
    out.push('\n');
    push_facets(&mut out, e)?;
    push_observations(&mut out, e)?;
    push_connections(&mut out, public, &e.slug)?;
    push_note(&mut out, project, &e.slug)?;
    out.push_str(FOOTER);
    Ok(out)
}

fn push_facets(out: &mut String, e: &EntityRec) -> Result<(), Error> {
    let lines = facet_lines(e)?;
    if lines.is_empty() {
        return Ok(());
    }
    out.push_str("## Facets\n\n");
    for line in &lines {
        out.push_str(line);
        out.push('\n');
    }
    out.push('\n');
    Ok(())
}

fn facet_lines(e: &EntityRec) -> Result<Vec<String>, Error> {
    let mut lines: Vec<String> = Vec::new();
    let role = role_of(&e.facets)?;
    if role != Role::Unset {
        lines.push(format!("- **Role:** {}", ROLE_META[role as usize].label));
    }
    let occ = occupation_of(&e.facets)?;
    lines.extend(occ.map(|o| format!("- **Occupation:** {}", o.label)));
    for facet in [
        Facet::OrgType,
        Facet::AccountType,
        Facet::DomainType,
        Facet::SiteType,
        Facet::ClaimType,
    ] {
        let Some(i) = subtype_of(&e.facets, facet)? else {
            continue;
        };
        let Some(v) = subtype_value(facet, i)? else {
            continue;
        };
        lines.push(format!("- **{}:** {}", FACET_META[facet as usize].label, v.label));
    }
    Ok(lines)
}

fn push_observations(out: &mut String, e: &EntityRec) -> Result<(), Error> {
    let visible: Vec<_> = e.observations.iter().filter(|o| !o.sealed).collect();
    if visible.is_empty() {
        return Ok(());
    }
    out.push_str("## Observations\n\n");
    for o in &visible {
        out.push_str(&format!("### {}\n\n", pretty_key(&o.name)?));
        out.push_str(&format!("{}\n\n", o.value.text()?));
        out.push_str(&format!(
            "*{} · {}% confidence · {}*\n",
            status_label(o.status)?,
            o.confidence,
            origin_label(&o.origin),
        ));
        push_sources(out, &o.sources, "")?;
        out.push('\n');
    }
    Ok(())
}

fn origin_label(origin: &Origin) -> String {
    match origin {
        Origin::Manual => "manual".to_owned(),
        Origin::Lookup(module) => format!("via {module}"),
        Origin::Import(src) => format!("import · {src}"),
        Origin::Inference => "inferred".to_owned(),
    }
}

fn push_connections(out: &mut String, public: &CaseFile, slug: &str) -> Result<(), Error> {
    let incident: Vec<_> = public
        .data
        .relations
        .iter()
        .filter(|r| r.from == slug || r.to == slug)
        .collect();
    if incident.is_empty() {
        return Ok(());
    }
    out.push_str("## Connections\n\n");
    for r in &incident {
        let outbound = r.from == slug;
        let other = if outbound { &r.to } else { &r.from };
        let endpoint = describe_endpoint(public, other)?;
        let verb = RELATION_META[r.kind as usize].label;
        let head = if outbound {
            format!("—**{verb}**→ {endpoint}")
        } else {
            format!("←**{verb}**— {endpoint}")
        };
        out.push_str(&format!("- {head} · {}{}\n", source_badge(r), window_label(r)?));
        push_sources(out, &r.sources, "  ")?;
    }
    out.push('\n');
    Ok(())
}

fn describe_endpoint(public: &CaseFile, slug: &str) -> Result<String, Error> {
    let Some(e) = public.data.entities.iter().find(|e| e.slug == slug) else {
        return Ok(format!("`{slug}`"));
    };
    Ok(format!("{} **{}**", KIND_META[e.kind as usize].icon, e.label))
}

fn source_badge(r: &RelationRec) -> String {
    let n = r.sources.iter().filter(|s| !s.sealed).count();
    if n == 0 {
        return "⚠ unsourced".to_owned();
    }
    format!("📎 {n}")
}

fn window_label(r: &RelationRec) -> Result<String, Error> {
    if r.valid_from.is_none() && r.valid_to.is_none() {
        return Ok(String::new());
    }
    let span = ObsValue::DateRange {
        start: r.valid_from,
        end: r.valid_to,
    }
    .text()?;
    Ok(format!(" · {span}"))
}

fn push_sources(out: &mut String, sources: &[Source], indent: &str) -> Result<(), Error> {
    let visible: Vec<_> = sources.iter().filter(|s| !s.sealed).collect();
    if visible.is_empty() {
        return Ok(());
    }
    for s in &visible {
        out.push_str(&format!(
            "{indent}- 📎 {} · {} — `{}`\n",
            SOURCE_TIER_META[s.tier as usize].label,
            SOURCE_META[s.kind as usize].label,
            s.reference,
        ));
        let excerpt = s.excerpt.trim();
        if !excerpt.is_empty() {
            out.push_str(&format!("{indent}  > {excerpt}\n"));
        }
    }
    Ok(())
}

fn push_note(out: &mut String, project: &Project, slug: &str) -> Result<(), Error> {
    let note = read_note(project, slug)?;
    let trimmed = note.trim();
    if trimmed.is_empty() {
        return Ok(());
    }
    out.push_str("## Note\n\n");
    out.push_str(trimmed);
    out.push('\n');
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{
        Author, CaseMeta, EntityKind, ObsValue, Observation, RelationKind, SourceKind,
        SourceTier, Verification,
    };
    use crate::project::io::{write_case, write_note};

    fn tmp_project(name: &str) -> Project {
        let d = std::env::temp_dir()
            .join(format!("redstring_dossier_{name}_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        Project::create(&d).unwrap()
    }

    fn obs(name: &str, value: &str, sealed: bool) -> Observation {
        let mut o = Observation::stamp(
            name.to_owned(),
            ObsValue::Text(value.to_owned()),
            Origin::Manual,
            Verification::AnalystAsserted,
            Author::default(),
        )
        .unwrap();
        o.sealed = sealed;
        o
    }

    fn ent(slug: &str, kind: EntityKind, label: &str, value: &str, sealed: bool) -> EntityRec {
        EntityRec {
            slug: slug.to_owned(),
            kind,
            label: label.to_owned(),
            value: value.to_owned(),
            sealed,
            observations: vec![],
            facets: Default::default(),
            image: None,
        }
    }

    fn rel(from: &str, to: &str, kind: RelationKind, sources: Vec<Source>) -> RelationRec {
        RelationRec {
            from: from.to_owned(),
            to: to.to_owned(),
            kind,
            origin: Origin::Manual,
            status: Verification::AnalystAsserted,
            confidence: 100,
            author: Author::default(),
            created_at: 0,
            sources,
            valid_from: None,
            valid_to: None,
            sealed: false,
        }
    }

    fn all_dossiers(project: &Project) -> Vec<(String, String)> {
        let mut out = Vec::new();
        let dir = project.root.join("entities");
        for entry in std::fs::read_dir(&dir).unwrap() {
            let entry = entry.unwrap();
            if !entry.file_type().unwrap().is_dir() {
                continue;
            }
            let path = entry.path().join("dossier.md");
            if !path.exists() {
                continue;
            }
            let slug = entry.file_name().to_string_lossy().into_owned();
            out.push((slug, std::fs::read_to_string(&path).unwrap()));
        }
        out
    }

    #[test]
    fn sealed_data_never_leaks_into_any_dossier() {
        let p = tmp_project("safety");
        let mut cf = CaseFile::default();
        cf.meta = CaseMeta::stamped("safety").unwrap();

        let mut victim = ent(
            "secret_entity",
            EntityKind::Person,
            "SECRETDOSSIERNAME",
            "secret_dossier_value",
            true,
        );
        victim.observations = vec![obs("hidden_fact", "SECRETOBSLEAK", false)];

        let mut auditor = ent("auditor", EntityKind::Person, "The Auditor", "", false);
        auditor.observations = vec![
            obs("informant", "SEALEDOBSVALUE", true),
            obs("public_role", "Compliance Officer", false),
        ];

        let shell = ent("shell", EntityKind::Organization, "Shell Co", "", false);

        cf.data.entities.push(victim);
        cf.data.entities.push(auditor);
        cf.data.entities.push(shell);

        cf.data.relations.push(rel(
            "secret_entity",
            "auditor",
            RelationKind::Controls,
            vec![],
        ));
        cf.data.relations.push(rel(
            "auditor",
            "shell",
            RelationKind::Controls,
            vec![
                Source {
                    kind: SourceKind::Note,
                    reference: "SEALEDDOSSIERREF".to_owned(),
                    excerpt: "SEALEDEXCERPTLEAK".to_owned(),
                    sealed: true,
                    ..Default::default()
                },
                Source {
                    kind: SourceKind::Document,
                    reference: "evidence/docs/public-filing.pdf".to_owned(),
                    ..Default::default()
                },
            ],
        ));

        write_case(&p, &cf).unwrap();
        write_note(&p, "secret_entity", "SECRETNOTELEAK — do not publish\n").unwrap();
        write_note(&p, "auditor", "an honest broker\n").unwrap();
        write_dossiers(&p, &cf).unwrap();

        let sentinels = [
            "SECRETDOSSIERNAME",
            "secret_dossier_value",
            "SECRETOBSLEAK",
            "SECRETNOTELEAK",
            "SEALEDOBSVALUE",
            "SEALEDDOSSIERREF",
            "SEALEDEXCERPTLEAK",
        ];
        let dossiers = all_dossiers(&p);
        assert_eq!(dossiers.len(), 3, "every entity dir gets a dossier: {dossiers:?}");
        for (slug, body) in &dossiers {
            for leak in sentinels {
                assert!(
                    !body.contains(leak),
                    "dossier for {slug} leaked sealed sentinel '{leak}':\n{body}"
                );
            }
        }

        let stub = std::fs::read_to_string(p.entity_dir("secret_entity").unwrap().join("dossier.md"))
            .unwrap();
        assert!(stub.contains("[sealed]"), "the sealed entity dossier is a stub: {stub}");

        let aud = std::fs::read_to_string(p.entity_dir("auditor").unwrap().join("dossier.md"))
            .unwrap();
        assert!(aud.contains("Compliance Officer"), "an unsealed obs survives: {aud}");
        assert!(
            aud.contains("evidence/docs/public-filing.pdf"),
            "the unsealed source on the edge survives: {aud}"
        );
        assert!(aud.contains("Shell Co"), "the unsealed connection survives: {aud}");
        assert!(
            !aud.contains("[sealed]"),
            "the edge to the sealed entity is dropped, not aliased into the dossier: {aud}"
        );

        std::fs::remove_dir_all(p.root).unwrap();
    }

    #[test]
    fn unsealed_dossier_carries_label_observation_and_sourced_connection() {
        let p = tmp_project("content");
        let mut cf = CaseFile::default();
        cf.meta = CaseMeta::stamped("content").unwrap();

        let mut doe = ent("doe", EntityKind::Person, "J. Doe", "john@doe.example", false);
        doe.observations = vec![obs("dob", "1971-03-04", false)];
        crate::model::set_role(&mut doe.facets, Role::Suspect).unwrap();

        cf.data.entities.push(doe);
        cf.data
            .entities
            .push(ent("shell", EntityKind::Organization, "Shell Co", "", false));
        cf.data.relations.push(rel(
            "doe",
            "shell",
            RelationKind::Controls,
            vec![Source {
                kind: SourceKind::Document,
                reference: "evidence/docs/filing.pdf".to_owned(),
                tier: SourceTier::Primary,
                ..Default::default()
            }],
        ));

        write_case(&p, &cf).unwrap();
        write_note(&p, "doe", "person of interest\n").unwrap();
        write_dossiers(&p, &cf).unwrap();

        let body =
            std::fs::read_to_string(p.entity_dir("doe").unwrap().join("dossier.md")).unwrap();
        assert!(body.contains("J. Doe"), "header carries the label: {body}");
        assert!(body.contains("john@doe.example"), "header carries the typed value: {body}");
        assert!(body.contains("**Role:** suspect"), "the role facet renders: {body}");
        assert!(body.contains("## Observations"), "observations section present: {body}");
        assert!(body.contains("1971-03-04"), "the observation value renders: {body}");
        assert!(body.contains("## Connections"), "connections section present: {body}");
        assert!(body.contains("Shell Co"), "the connection endpoint renders: {body}");
        assert!(
            body.contains("evidence/docs/filing.pdf"),
            "the connection's source is cited: {body}"
        );
        assert!(body.contains("## Note"), "the note is inlined: {body}");
        assert!(body.contains("person of interest"), "the note prose renders: {body}");

        std::fs::remove_dir_all(p.root).unwrap();
    }

    #[test]
    fn unsourced_connection_is_flagged() {
        let p = tmp_project("unsourced");
        let mut cf = CaseFile::default();
        cf.meta = CaseMeta::stamped("unsourced").unwrap();
        cf.data
            .entities
            .push(ent("a", EntityKind::Person, "Ana", "", false));
        cf.data
            .entities
            .push(ent("b", EntityKind::Person, "Bob", "", false));
        cf.data
            .relations
            .push(rel("a", "b", RelationKind::Controls, vec![]));

        write_case(&p, &cf).unwrap();
        write_dossiers(&p, &cf).unwrap();

        let body = std::fs::read_to_string(p.entity_dir("a").unwrap().join("dossier.md")).unwrap();
        assert!(body.contains("⚠ unsourced"), "a zero-source edge is flagged: {body}");

        std::fs::remove_dir_all(p.root).unwrap();
    }
}
